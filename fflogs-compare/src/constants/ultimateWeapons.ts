// Source: https://ffxiv.consolegameswiki.com/wiki/Ultimate_Raid_Weapons
// weapons: the item id of each combat job's weapon (job names as in constants/jobs.ts), for its icon and name from XIVAPI.
// Found on XIVAPI by exact name (the paladin's sword; its shield isn't tracked). Jobs released after an ultimate have no
// weapon from it and are left out.
// totem: what a clear drops, traded one for one for any job's weapon from that ultimate (item id for its icon)
// encounters: its FF Logs encounter ids. Each re-release in a later expansion's (legacy) zone got a new one, so a
